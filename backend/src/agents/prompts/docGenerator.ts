/**
 * 构建用户提示词
 * @param description 产品描述
 * @param reportJson 市场调研报告 JSON
 * @param projectName 项目名称
 * @param version 版本: mvp / full
 * @param techStackJson 已选技术栈 JSON (可选)
 * @param frontendDesignJson 已选前端设计方案 JSON (可选)
 * @param businessModel 商业模式说明 (可选,用于 MVP 版本)
 */
export function buildDocGenerationUserPrompt(
  description: string,
  reportJson: string,
  projectName: string,
  version: 'mvp' | 'full' = 'full',
  techStackJson?: string,
  frontendDesignJson?: string,
  businessModel?: string
): string {
  const parts: string[] = [];

  parts.push(`## 项目名称
${projectName}

## 产品想法描述
${description}

## 市场调研报告 (完整 JSON)
${reportJson}`);

  if (techStackJson) {
    parts.push(`## 已选定的技术栈方案 (请严格基于此方案生成技术相关文档)
${techStackJson}

重要:技术架构设计、功能模块设计、数据库设计、API 文档等所有技术相关文档,必须严格使用上述选定的技术栈,不要自行更换或推荐其他技术。`);
  }

  if (frontendDesignJson) {
    parts.push(`## 已选定的前端设计方案 (请在 PRD 和前端相关设计中体现)
${frontendDesignJson}

重要:在产品需求文档、功能模块设计中,要体现选定的设计风格、交互模式和响应式策略。`);
  }

  if (version === 'mvp' && businessModel) {
    parts.push(`## 商业模式参考 (用于定义 MVP 边界和验证目标)
${businessModel}

重要:MVP 的功能范围和验证指标要结合商业模式来定义,明确 MVP 阶段要验证的核心商业假设。`);
  }

  parts.push(`---

请基于以上项目信息,生成${version === 'mvp' ? '8 份 MVP' : '10 份完整'}开发文档,按 JSON 格式输出。`);

  return parts.join('\n\n');
}
